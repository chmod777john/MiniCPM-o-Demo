/** Generate the mobile shell from the desktop DOM required by omni-app.js. */
import { readFile, writeFile } from 'node:fs/promises'
const desktopUrl = new URL('../../../static/omni/omni.html', import.meta.url)
const mobileUrl = new URL('../../../static/mobile-omni/index.html', import.meta.url)
const desktop = await readFile(desktopUrl, 'utf8')
const mobile = desktop
  .replace('width=device-width, initial-scale=1.0', 'width=device-width, initial-scale=1.0, viewport-fit=cover, maximum-scale=1.0, user-scalable=no')
  .replace(/<title>[^<]*<\/title>/, '<title>MiniCPM-o · Mobile Omni</title>')
  .replace('</head>', '    <meta name="apple-mobile-web-app-capable" content="yes">\n    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">\n    <link rel="stylesheet" href="/static/mobile-omni/mobile-omni.css">\n    <link rel="stylesheet" href="/static/mobile-omni/settings-widget.css">\n</head>')
  .replace('<body>', '<body class="video-fullscreen mobile-omni">')
  .replace('</body>', '<script src="/static/mobile-omni/settings-widget.js"></script>\n<script type="module" src="/static/mobile-omni/mobile-bridge.js"></script>\n</body>')
await writeFile(mobileUrl, '<!-- Generated by frontend/mobile/scripts/sync-omni-shell.mjs; edit the desktop DOM or mobile CSS/bridge. -->\n' + mobile)
console.log('Synced mobile Omni shell')
